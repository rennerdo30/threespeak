#!/usr/bin/env node
/**
 * Threespeak build script.
 *
 * Compiles the two theme variants from src/ into self-contained CSS files
 * (the TeamSpeak extension loader expects one flat CSS file per variant and
 * relative @import is not something we want to rely on inside the client's
 * custom URL scheme). Also renders the preview SVGs from a shared template.
 *
 * Usage:  node build.mjs [--verbose]
 */
import { readFile, writeFile, mkdir, appendFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC_DIR = join(ROOT, "src");
const LOG_DIR = join(ROOT, "logs");
const LOG_FILE = join(LOG_DIR, "build.log");
const STRUCTURE_FILE = join(SRC_DIR, "structure.css");
const PREVIEW_TEMPLATE_FILE = join(SRC_DIR, "preview.template.svg");
const STACKED_LAYOUT_FILE = join(SRC_DIR, "layout-stacked.css");
/** Font files referenced from structure.css. They are inlined as data URIs because the
 *  client serves the theme from a different origin than the page, and cross-origin font
 *  files are refused without CORS headers. */
const FONT_DIR = join(ROOT, "fonts");
const FONT_URL_PATTERN = /url\("fonts\/([^"]+)"\)/g;
const FONT_MIME = "font/woff2";
const BANNER_TEMPLATE = "/* Threespeak {variant} v{version} — generated by build.mjs on {date}. Edit src/ instead. */\n";

/** Variants: token file, output CSS, output preview and the preview colours. */
const VARIANTS = [
    {
        id: "light",
        label: "Light",
        tokens: join(SRC_DIR, "tokens-light.css"),
        css: join(ROOT, "threespeak-light.css"),
        preview: join(ROOT, "preview-light.svg"),
    },
    {
        id: "dark",
        label: "Dark",
        tokens: join(SRC_DIR, "tokens-dark.css"),
        css: join(ROOT, "threespeak-dark.css"),
        preview: join(ROOT, "preview-dark.svg"),
    },
    {
        id: "light-stacked",
        label: "Light, chat below",
        tokens: join(SRC_DIR, "tokens-light.css"),
        css: join(ROOT, "threespeak-light-stacked.css"),
        preview: join(ROOT, "preview-light.svg"),
        layout: STACKED_LAYOUT_FILE,
    },
    {
        id: "dark-stacked",
        label: "Dark, chat below",
        tokens: join(SRC_DIR, "tokens-dark.css"),
        css: join(ROOT, "threespeak-dark-stacked.css"),
        preview: join(ROOT, "preview-dark.svg"),
        layout: STACKED_LAYOUT_FILE,
    },
];

/** Preview colours are read from the theme-own `--ts3-*` tokens of each variant. */
const PREVIEW_TOKEN_MAP = {
    ground: "--ts3-ground",
    chrome: "--ts3-chrome",
    raised: "--ts3-chrome-raised",
    border: "--ts3-border",
    text: "--ts3-text",
    muted: "--ts3-text-muted",
    accent: "--ts3-accent",
    hover: "--ts3-hover",
    selection: "--ts3-selection",
    online: "--ts3-online",
    away: "--ts3-away",
    silent: "--ts3-client-silent-1",
    talking: "--ts3-client-talking-1",
};

const LEVELS = { debug: 10, info: 20, warn: 30, error: 40 };
const verbose = process.argv.includes("--verbose");
const consoleLevel = verbose ? LEVELS.debug : LEVELS.info;

async function log(level, message) {
    const line = `${new Date().toISOString()} [${level.toUpperCase()}] ${message}`;
    if (LEVELS[level] >= consoleLevel) {
        (level === "error" ? console.error : console.log)(line);
    }
    try {
        await appendFile(LOG_FILE, line + "\n");
    } catch {
        /* logging must never break the build */
    }
}

function readTokenValue(tokensCss, name) {
    const match = tokensCss.match(new RegExp(`${name}\\s*:\\s*([^;!]+)`));
    if (!match) {
        throw new Error(`Token ${name} is missing from the token file`);
    }
    return match[1].trim();
}

function checkBraceBalance(css, label) {
    let depth = 0;
    for (const ch of css) {
        if (ch === "{") depth++;
        if (ch === "}") depth--;
        if (depth < 0) throw new Error(`${label}: unbalanced braces (closing before opening)`);
    }
    if (depth !== 0) throw new Error(`${label}: unbalanced braces (depth ${depth} at end of file)`);
}

async function inlineFonts(css) {
    const matches = [...css.matchAll(FONT_URL_PATTERN)];
    for (const match of matches) {
        const file = join(FONT_DIR, match[1]);
        const data = await readFile(file);
        await log("debug", `Inlining font ${match[1]} (${data.length} bytes)`);
        css = css.replace(match[0], `url("data:${FONT_MIME};base64,${data.toString("base64")}")`);
    }
    return css;
}

async function buildVariant(variant, structure, previewTemplate, version) {
    await log("debug", `Reading tokens for ${variant.id} from ${variant.tokens}`);
    const tokens = await readFile(variant.tokens, "utf8");
    checkBraceBalance(tokens, variant.tokens);

    const banner = BANNER_TEMPLATE
        .replace("{variant}", variant.label)
        .replace("{version}", version)
        .replace("{date}", new Date().toISOString().slice(0, 10));
    let layout = "";
    if (variant.layout) {
        layout = await readFile(variant.layout, "utf8");
        checkBraceBalance(layout, variant.layout);
        await log("debug", `Appending layout ${variant.layout} for ${variant.id}`);
    }
    const css = banner + tokens.trimEnd() + "\n\n" + structure.trimEnd() + "\n" + (layout ? "\n" + layout.trimEnd() + "\n" : "");
    await writeFile(variant.css, css, "utf8");
    await log("info", `Wrote ${variant.css} (${css.length} bytes)`);

    let svg = previewTemplate.replaceAll("{{VARIANT}}", variant.label);
    for (const [placeholder, tokenName] of Object.entries(PREVIEW_TOKEN_MAP)) {
        const value = readTokenValue(tokens, tokenName);
        await log("debug", `Preview ${variant.id}: ${placeholder} = ${value}`);
        svg = svg.replaceAll(`{{${placeholder}}}`, value);
    }
    const leftover = svg.match(/\{\{[a-zA-Z]+\}\}/g);
    if (leftover) {
        throw new Error(`Preview template has unresolved placeholders: ${[...new Set(leftover)].join(", ")}`);
    }
    if (variant.layout) {
        await log("debug", `Preview for ${variant.id} is shared with its base variant`);
        return;
    }
    await writeFile(variant.preview, svg, "utf8");
    await log("info", `Wrote ${variant.preview}`);
}

async function main() {
    await mkdir(LOG_DIR, { recursive: true });
    await log("info", "Build started");

    const pkg = JSON.parse(await readFile(join(ROOT, "package.json"), "utf8"));
    const structure = await inlineFonts(await readFile(STRUCTURE_FILE, "utf8"));
    checkBraceBalance(structure, STRUCTURE_FILE);
    const previewTemplate = await readFile(PREVIEW_TEMPLATE_FILE, "utf8");

    for (const variant of VARIANTS) {
        await buildVariant(variant, structure, previewTemplate, pkg.version);
    }
    await log("info", "Build finished");
}

main().catch(async (error) => {
    await log("error", error.stack ?? String(error));
    process.exitCode = 1;
});
